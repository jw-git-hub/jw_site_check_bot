# Иконка @jw_site_check_bot — «Проверка сайта»: окно браузера с галочкой внутри.
# Смысл — «сайт → отчёт». Пропорции сняты с уже выбранной владельцем аватарки бота
# (окно с тремя точками в шапке и галочкой), нарисована в той же технике, что icon.py
# соседа: векторные элементы, та же система толщины линий.
# Координаты — в пространстве аватарки 800×800 (центр кольца 400,400); окно центрировано на 400,400.
# Толщина линий — как у кольца (SW=21), углы скруглены.
# Порядок элементов = порядок волны яркости: окно браузера → точки вкладки → галочка (как читается страница).
SW = 21

WINDOW = [(255, 300), (545, 300), (545, 500), (255, 500)]
DIVIDER = [(255, 350), (545, 350)]
DOTS = [(285, 321), (317, 321), (349, 321)]
DOT_R = 9
CHECK = [(335, 435), (385, 475), (465, 395)]


def _dot(d, P, p, r):
    x, y = P(*p)
    d.ellipse([x - r, y - r, x + r, y + r], fill=255)


def _poly(d, P, w, pts, closed=False):
    seq = pts + pts[:1] if closed else pts
    for a, b in zip(seq, seq[1:]):
        d.line([P(*a), P(*b)], fill=255, width=int(w))
    for p in pts:                       # скруглённые углы и концы
        _dot(d, P, p, w / 2)


def window(d, P, w):
    _poly(d, P, w, WINDOW, closed=True)
    _poly(d, P, w, DIVIDER)


def dots(d, P, w):
    r = DOT_R * w / SW
    for p in DOTS:
        _dot(d, P, p, r)


def check(d, P, w):
    _poly(d, P, w, CHECK)


ELEMENTS = [window, dots, check]
